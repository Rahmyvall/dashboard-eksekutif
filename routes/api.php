<?php

declare (strict_types = 1);

use App\Http\Controllers\Api\BranchApiController;
use App\Http\Controllers\Api\RoleApiController;
use Illuminate\Support\Facades\Route;

/*
|--------------------------------------------------------------------------
| Role API
|--------------------------------------------------------------------------
*/

Route::prefix('roles')
    ->name('api.roles.')
    ->group(function () {

        /*
        |--------------------------------------------------------------------------
        | GET ALL ROLE
        |--------------------------------------------------------------------------
        */

        Route::get(
            '/',
            [
                RoleApiController::class,
                'index',
            ]
        )
            ->name('index');

        /*
        |--------------------------------------------------------------------------
        | CREATE ROLE
        |--------------------------------------------------------------------------
        */

        Route::post(
            '/',
            [
                RoleApiController::class,
                'store',
            ]
        )
            ->name('store');

        /*
        |--------------------------------------------------------------------------
        | DETAIL ROLE
        |--------------------------------------------------------------------------
        */

        Route::get(
            '/{role}',
            [
                RoleApiController::class,
                'show',
            ]
        )
            ->name('show');

        /*
        |--------------------------------------------------------------------------
        | UPDATE ROLE
        |--------------------------------------------------------------------------
        */

        Route::put(
            '/{role}',
            [
                RoleApiController::class,
                'update',
            ]
        )
            ->name('update');

        /*
        |--------------------------------------------------------------------------
        | DELETE ROLE
        |--------------------------------------------------------------------------
        */

        Route::delete(
            '/{role}',
            [
                RoleApiController::class,
                'destroy',
            ]
        )
            ->name('destroy');

    });

